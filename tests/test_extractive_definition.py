"""Glossary entry parsing and source-backed definition answers."""
import unittest

import _bootstrap

from retrieval import extract_exact_definition
from service import RAGService

PASSAGE = '''Chapter 5 − Project Scope Management

In the project context, the term scope can refer to:

•
Product scope. The features and functions that characterize a product,
service, or result

•
Project scope. The work that needs to be accomplished to deliver a product,
service, or result with the specified features and functions.

This chapter focuses on the processes used to manage the project scope.'''


def chunk(text=PASSAGE):
    return dict(id='source119', text=text, metadata=dict(source_doc='pmbok3',
                document_title='PMBOK Guide', edition='3rd edition', page_number=119))


class ExtractiveTests(unittest.TestCase):
    def test_exact_definition_from_page(self):
        result = extract_exact_definition(
            'What is project scope according to the PMBOK Guide?', chunk())
        self.assertEqual(
            result, 'Project scope. The work that needs to be accomplished to deliver a product, service, or result with the specified features and functions.')
        self.assertIn(result, ' '.join(PASSAGE.split()))
        self.assertNotIn('Product scope', result)

    def test_no_scope_statement_substitution(self):
        self.assertIsNone(extract_exact_definition('What is project scope?', chunk(
            'Project Scope Statement. A narrative description of project scope and deliverables.')))

    def test_no_incomplete_or_cross_reference_definition(self):
        for text in ('Project scope. The work that needs to be accomplished to deliver',
                     'Project scope. See the detailed explanation in Appendix F.'):
            self.assertIsNone(extract_exact_definition('What is project scope?', chunk(text)))

    def test_complex_question_stays_on_generative_path(self):
        self.assertIsNone(extract_exact_definition(
            'How does project scope differ from product scope?', chunk()))
        self.assertIsNone(extract_exact_definition(
            'What is project scope and how is it controlled?', chunk()))

    def test_acronym_annotated_entry_matches_full_term_and_alias(self):
        source = chunk(
            'Work Breakdown Structure (WBS) [Output/Input]. A hierarchy of project deliverables decomposed into manageable work packages.')
        for question in ('What is a work breakdown structure?', 'What is WBS?'):
            definition = extract_exact_definition(question, source)
            self.assertIsNotNone(definition, question)
            self.assertIn('hierarchy of project deliverables', definition)
            self.assertIn(definition, ' '.join(source['text'].split()))

    def test_wbs_primary_input_heading_is_not_definition(self):
        from retrieval import is_direct_definition
        source = chunk('Chapter 6 − Project Time Management\n\n.4 \nWork Breakdown Structure \nThe work breakdown structure (Section 5.3.3.2) is a primary input to schedule \nactivity definition.\n\n.5 \nWBS Dictionary')
        question = 'What is a work breakdown structure?'
        self.assertIsNone(extract_exact_definition(question, source))
        self.assertFalse(is_direct_definition(question, source))

    def test_wbs_generated_document_heading_is_not_definition(self):
        from retrieval import is_direct_definition
        source = chunk('5\n\n.2 \nWork Breakdown Structure \nThe key document generated by the Create WBS process is the actual WBS. Each \nWBS component is assigned a unique identifier.')
        self.assertFalse(is_direct_definition('What is a work breakdown structure?', source))

    def test_ranking_prefers_acronym_definition_over_usage(self):
        from retrieval import Reranker
        source = chunk(
            'Work Breakdown Structure (WBS) [Output/Input]. A hierarchy of project deliverables decomposed into manageable work packages.')
        usage = chunk(
            'Work Breakdown Structure\nThe work breakdown structure is a primary input to schedule activity definition.')

        class Model:
            def predict(self, pairs):
                return [6.37, 4.7]
        ranked = Reranker(Model()).rerank('What is a work breakdown structure?', [usage, source])
        self.assertEqual(ranked[0]['text'], source['text'])
        self.assertTrue(ranked[0]['definition_match'])
        self.assertFalse(ranked[1]['definition_match'])

    def test_subproject_fragment_is_not_wbs_definition(self):
        fragment = ('work breakdown structure. A subproject can be referred to as a project, '
                    'managed as a project, and acquired from a seller. May be referred to '
                    'as a subnetwork in a project schedule network diagram.')
        self.assertIsNone(extract_exact_definition(
            'What is a work breakdown structure?', chunk(fragment)))

    def test_uppercase_wrapped_continuation_is_not_an_entry(self):
        fragment = ('A subproject is a smaller portion of the project divided into a lower level of the\n'
                    'Work Breakdown Structure. A subproject can be managed as a project.')
        self.assertIsNone(extract_exact_definition(
            'What is a work breakdown structure?', chunk(fragment)))

    def test_wbs_and_stakeholder_glossary_entries_survive(self):
        cases = [
            ('work breakdown structure',
             'Work Breakdown Structure (WBS) [Output/Input]. A deliverable-oriented hierarchical decomposition of the work to be executed by the project team to accomplish the project objectives and create the required deliverables. It organizes and defines the total scope of the project.'),
            ('stakeholder', 'Stakeholder. Person or organization (e.g., customer, sponsor, performing organization, or the public) that is actively involved in the project, or whose interests may be positively or negatively affected by execution or completion of the project. A stakeholder may also exert influence over the project and its deliverables.')]
        for term, source in cases:
            self.assertEqual(extract_exact_definition(
                'What is ' + term + '?', chunk(source)), source)

    def test_exact_source_definition_does_not_call_llm(self):
        source = chunk()

        class Retriever:
            def search(self, *args, **kwargs):
                return [source]

        class Reranker:
            def rerank(self, query, chunks, **kwargs):
                return [dict(c, rerank_score=7.15) for c in chunks]

        class ForbiddenLLM:
            def generate(self, *args):
                raise AssertionError('Simple exact definition must skip generation')
        result = RAGService(None, Retriever(), Reranker(), ForbiddenLLM()).answer(
            'What is project scope according to the PMBOK Guide?')
        self.assertFalse(result.refused)
        self.assertEqual(result.diagnostics['reason'], 'extractive_definition')
        self.assertEqual(result.sources[0]['metadata']['page_number'], 119)
        self.assertTrue(result.answer.endswith('[S1]'))


if __name__ == '__main__':
    unittest.main()
